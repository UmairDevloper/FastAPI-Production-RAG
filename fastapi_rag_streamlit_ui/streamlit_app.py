def render_citations(citations):
    if not citations:
        st.info("The API returned no citations for this answer.")
        return
    for index, citation in enumerate(citations, start=1):
        title = citation.get("page_title") or "FastAPI documentation source"
        heading = citation.get("heading_path") or "Heading not provided"
        evidence_id = citation.get("evidence_id") or "Evidence ID not provided"
        source_url = citation.get("source_url")
        st.markdown('<div class="source-card">', unsafe_allow_html=True)
        st.markdown(f'<div class="source-title">Source {index}: {title}</div>', unsafe_allow_html=True)
        st.caption(f"Heading: {heading}")
        st.caption(f"Evidence ID: {evidence_id}")
        if source_url:
            parsed = urlparse(source_url)
            if parsed.scheme in ("http", "https") and parsed.netloc:
                st.markdown(f"[Open official source ↗]({source_url})")
            else:
                st.warning("A source URL was returned, but it is not a valid HTTP(S) link.")
        else:
            st.caption("No source URL supplied by the API.")
        st.markdown("</div>", unsafe_allow_html=True)

def ask_api(question: str):
    payload = {"question": question}
    started = time.perf_counter()
    try:
        with httpx.Client(timeout=httpx.Timeout(180.0, connect=5.0)) as client:
            response = client.post(ASK_URL, json=payload)
        elapsed_ms = (time.perf_counter() - started) * 1000
        if not response.is_success:
            detail = None
            try:
                detail = response.json().get("detail")
            except (ValueError, AttributeError):
                pass
            raise RuntimeError(
                f"API returned HTTP {response.status_code}"
                + (f": {detail}" if detail else "")
            )
        data = response.json()
        data["_ui_elapsed_ms"] = round(elapsed_ms, 2)
        return data
    except httpx.TimeoutException as exc:
        raise RuntimeError("The API request timed out. Check the backend logs and try again.") from exc
    except httpx.HTTPError as exc:
        raise RuntimeError(f"Could not connect to the FastAPI backend at {API_BASE_URL}.") from exc
    except ValueError as exc:
        raise RuntimeError("The API returned invalid JSON.") from exc

