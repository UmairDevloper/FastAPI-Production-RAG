question = st.chat_input("Ask a question about FastAPI…")
if not question and st.session_state.get("pending_question"):
    question = st.session_state.pop("pending_question")

if question:
    question = question.strip()
    if not question:
        st.warning("Please enter a non-empty question.")
    elif len(question) > 2000:
        st.warning("The API accepts questions up to 2,000 characters.")
    else:
        st.session_state.messages.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)
        with st.chat_message("assistant"):
            with st.spinner("Searching documentation and generating an answer…"):
                try:
                    result = ask_api(question)
                    answer = result.get("answer") or "The API returned an empty answer."
                    st.markdown(answer)
                    if result.get("insufficient_evidence"):
                        st.warning("The API marked this response as having insufficient evidence. Verify the sources before relying on it.")
                    with st.expander("Sources and citation metadata", expanded=True):
                        render_citations(result.get("citations") or [])
                    latency = result.get("latency_ms") or {}
                    metrics = {
                        "API pipeline latency_ms": latency,
                        "UI measured round-trip ms": result.get("_ui_elapsed_ms"),
                        "insufficient_evidence": result.get("insufficient_evidence"),
                    }
                    with st.expander("Response metrics", expanded=False):
                        st.json(metrics)
                    st.session_state.messages.append({
                        "role": "assistant",
                        "content": answer,
                        "citations": result.get("citations") or [],
                        "metrics": metrics,
                    })
                    st.session_state.last_response = result
                    st.session_state.last_question = question
                except RuntimeError as exc:
                    st.error(str(exc))
                    st.caption("The failed request is not stored as an assistant answer.")
        st.rerun()

